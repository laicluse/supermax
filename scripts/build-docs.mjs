import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = resolve(repoRoot, "src");
const targetDir = resolve(repoRoot, "docs/assets/supermax");
const checkOnly = process.argv.includes("--check");

const modules = (await readdir(sourceDir)).filter((name) => name.endsWith(".js") || name.endsWith(".css")).sort();
const expected = new Map();
for (const name of modules) {
	const source = await readFile(resolve(sourceDir, name), "utf8");
	const banner = name.endsWith(".css") ? `/* Generated from src/${name} by scripts/build-docs.mjs. Do not edit this file directly. */` : `// Generated from src/${name} by scripts/build-docs.mjs.\n// Do not edit this file directly.`;
	expected.set(name, `${banner}\n\n${source}`);
}
for (const name of await readdir(resolve(sourceDir, "fonts"))) expected.set(`fonts/${name}`, await readFile(resolve(sourceDir, "fonts", name)));

let current = [];
try {
	current = (await readdir(targetDir)).filter((name) => name.endsWith(".js") || name.endsWith(".css"));
	try { current.push(...(await readdir(resolve(targetDir, "fonts"))).map((name) => `fonts/${name}`)); }
	catch (error) { if (error.code !== "ENOENT") throw error; }
} catch (error) {
	if (error.code !== "ENOENT") throw error;
}

if (checkOnly) {
	const stale = [];
	for (const [name, generated] of expected) {
		let existing = null;
		try {
			existing = await readFile(resolve(targetDir, name), Buffer.isBuffer(generated) ? undefined : "utf8");
		} catch (error) {
			if (error.code !== "ENOENT") throw error;
		}
		if (Buffer.isBuffer(generated) ? !Buffer.isBuffer(existing) || !generated.equals(existing) : existing !== generated) stale.push(name);
	}
	for (const name of current) if (!expected.has(name)) stale.push(name);
	if (stale.length > 0) {
		console.error(`docs/assets/supermax is out of date (${stale.join(", ")}). Run \`corepack pnpm run build:docs\`.`);
		process.exit(1);
	}
	process.exit(0);
}

await mkdir(targetDir, { recursive: true });
for (const name of current) if (!expected.has(name)) await rm(resolve(targetDir, name));
for (const [name, generated] of expected) {
	await mkdir(dirname(resolve(targetDir, name)), { recursive: true });
	await writeFile(resolve(targetDir, name), generated);
}
