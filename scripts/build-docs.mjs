import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(repoRoot, "src/cell-collection.js");
const targetPath = resolve(repoRoot, "docs/assets/cell-collection.js");
const checkOnly = process.argv.includes("--check");

const source = await readFile(sourcePath, "utf8");
const generated = `// Generated from ../../src/cell-collection.js by scripts/build-docs.mjs.\n// Do not edit this file directly.\n\n${source}`;

let current = null;
try {
	current = await readFile(targetPath, "utf8");
} catch (error) {
	if (error.code !== "ENOENT") throw error;
}

if (checkOnly) {
	if (current !== generated) {
		console.error("docs/assets/cell-collection.js is out of date. Run `corepack pnpm run build:docs`.");
		process.exit(1);
	}
	process.exit(0);
}

await mkdir(dirname(targetPath), { recursive: true });
await writeFile(targetPath, generated);
